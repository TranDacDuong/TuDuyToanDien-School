ALTER TABLE public.app_permissions
  ADD COLUMN IF NOT EXISTS group_key text,
  ADD COLUMN IF NOT EXISTS group_label text,
  ADD COLUMN IF NOT EXISTS access_level text NOT NULL DEFAULT 'basic',
  ADD COLUMN IF NOT EXISTS is_sensitive boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS is_assignable boolean NOT NULL DEFAULT true;

ALTER TABLE public.app_permissions DROP CONSTRAINT IF EXISTS app_permissions_access_level_check;
ALTER TABLE public.app_permissions
  ADD CONSTRAINT app_permissions_access_level_check
  CHECK (access_level IN ('view', 'basic', 'full'));

CREATE TABLE IF NOT EXISTS public.permission_change_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  permission_key text NOT NULL,
  previous_value boolean,
  new_value boolean,
  changed_by uuid REFERENCES public.users(id) ON DELETE SET NULL,
  changed_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS permission_change_log_target_idx
  ON public.permission_change_log(target_user_id, changed_at DESC);

