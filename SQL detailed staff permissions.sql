        public.has_app_permission('tuition.collect') OR
        public.has_app_permission('tuition.notes.manage') OR
        public.has_app_permission('tuition.surplus.manage') OR
        public.has_app_permission('tuition.refund') OR
        public.has_app_permission('tuition.lock')
