      USING (
        public.mindup_is_admin(auth.uid())
        OR public.has_app_permission('tuition.view_all')
        OR student_id = auth.uid()
        OR EXISTS (
          SELECT 1 FROM public.parent_students ps
          WHERE ps.parent_id = auth.uid()
            AND ps.student_id = tuition_payments.student_id
            AND ps.revoked_at IS NULL
        )
        OR (
          public.has_app_permission('tuition.view_assigned')
          AND EXISTS (
            SELECT 1
            FROM public.class_students cs
            JOIN public.class_teachers ct ON ct.class_id = cs.class_id
            WHERE cs.student_id = tuition_payments.student_id
              AND ct.teacher_id = auth.uid()
              AND (cs.left_at IS NULL OR cs.left_at >= tuition_payments.month)
          )
        )
      );
  END IF;
END $$;

