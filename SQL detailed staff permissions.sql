CREATE OR REPLACE FUNCTION public.admin_set_user_permissions(
  p_user_id uuid,
  p_changes jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  change_item jsonb;
  key_value text;
  allowed_value boolean;
  old_value boolean;
BEGIN
  IF NOT public.mindup_is_admin(auth.uid()) THEN
    RAISE EXCEPTION 'Admin only';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.users WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'User not found';
  END IF;
  IF jsonb_typeof(p_changes) <> 'array' THEN
    RAISE EXCEPTION 'p_changes must be a JSON array';
  END IF;

  FOR change_item IN SELECT value FROM jsonb_array_elements(p_changes)
  LOOP
    key_value := change_item->>'permission_key';
    IF NOT EXISTS (
      SELECT 1 FROM public.app_permissions
      WHERE permission_key = key_value AND is_assignable = true
    ) THEN
      RAISE EXCEPTION 'Unknown or non-assignable permission: %', key_value;
    END IF;

    SELECT allowed INTO old_value
    FROM public.user_permission_overrides
    WHERE user_id = p_user_id AND permission_key = key_value;

    IF change_item->'allowed' IS NULL OR change_item->>'allowed' IS NULL THEN
      DELETE FROM public.user_permission_overrides
      WHERE user_id = p_user_id AND permission_key = key_value;
      allowed_value := NULL;
    ELSE
      allowed_value := (change_item->>'allowed')::boolean;
      INSERT INTO public.user_permission_overrides(user_id, permission_key, allowed, updated_by, updated_at)
      VALUES (p_user_id, key_value, allowed_value, auth.uid(), now())
      ON CONFLICT (user_id, permission_key) DO UPDATE SET
        allowed = EXCLUDED.allowed,
        updated_by = EXCLUDED.updated_by,
        updated_at = now();
    END IF;

    INSERT INTO public.permission_change_log
      (target_user_id, permission_key, previous_value, new_value, changed_by)
    VALUES (p_user_id, key_value, old_value, allowed_value, auth.uid());
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_user_permission(
  p_user_id uuid,
  p_permission_key text,
  p_allowed boolean DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM public.admin_set_user_permissions(
    p_user_id,
    jsonb_build_array(jsonb_build_object('permission_key', p_permission_key, 'allowed', p_allowed))
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_get_permission_management()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  result jsonb;
BEGIN
  IF NOT public.mindup_is_admin(auth.uid()) THEN
    RAISE EXCEPTION 'Admin only';
  END IF;

  SELECT jsonb_build_object(
    'catalog', COALESCE((
      SELECT jsonb_agg(to_jsonb(p) ORDER BY p.sort_order, p.permission_key)
      FROM public.app_permissions p
      WHERE p.is_assignable = true
    ), '[]'::jsonb),
    'role_defaults', COALESCE((
      SELECT jsonb_object_agg(role_name, permissions)
      FROM (
        SELECT role_name, jsonb_object_agg(permission_key, allowed) AS permissions
        FROM public.role_permission_defaults
        GROUP BY role_name
      ) role_rows
    ), '{}'::jsonb),
    'users', COALESCE((
      SELECT jsonb_agg(
        jsonb_build_object(
          'id', u.id, 'full_name', u.full_name, 'email', u.email, 'role', u.role::text,
          'overrides', COALESCE((
            SELECT jsonb_object_agg(o.permission_key, o.allowed)
            FROM public.user_permission_overrides o
            JOIN public.app_permissions p ON p.permission_key = o.permission_key
            WHERE o.user_id = u.id AND p.is_assignable = true
          ), '{}'::jsonb)
        ) ORDER BY u.full_name NULLS LAST, u.email
      )
      FROM public.users u
      WHERE u.role::text IN ('admin', 'teacher', 'assistant')
    ), '[]'::jsonb)
  ) INTO result;
  RETURN result;
END;
$$;

